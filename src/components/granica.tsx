// Рисунок для первого экрана: что такое граница и что такое удобность.
//
// Заказ владелицы 14.09.2026 - абстрактный рисунок, который отображает
// понятия удобности, границ, защиты себя и разламывания границы. Похожим на
// картинки сервиса «Ясно» он быть не должен, от них взята только идея, что
// у экрана есть иллюстрация.
//
// Как читается, без подписей:
//   - мягкий круг в центре и точка в нём - сам человек;
//   - чёткая линия вокруг - его граница;
//   - справа чужой кружок упирается в сплошную линию и остаётся снаружи -
//     граница удержана, человек себя отстоял;
//   - слева линия прерывается пунктиром, и через разрыв кружки один за другим
//     проходят внутрь - граница разламывается. Так и выглядит удобность:
//     чужое заходит туда, где должно было остаться своё.
//
// Нарисован кодом, а не вставлен картинкой. Так он весит несколько килобайт,
// одинаково чёткий на любом экране и берёт цвета из палитры - в тёмной теме
// перекрашивается сам.
//
// Геометрия. Круг-граница: центр (100, 72), радиус 40. Углы считаются как в
// SVG - от направления вправо по часовой стрелке. Разрыв слева занимает
// дугу от 150° до 230°:
//   230° -> (74.29, 41.36)     150° -> (65.36, 92.00)
// Сплошная часть идёт от 230° по часовой до 150° - это 280°, поэтому в
// команде дуги стоит флаг большой дуги.

export function Granica({ className = "" }: { className?: string }) {
  return (
    <svg
      viewBox="0 0 200 144"
      // Рисунок декоративный: всё, что он говорит, сказано в тексте экрана.
      // aria-hidden - чтобы экранный диктор не зачитывал набор кругов.
      aria-hidden="true"
      className={className}
      fill="none"
    >
      {/* Сам человек: мягкая заливка внутри границы и точка в центре. */}
      <circle cx="100" cy="72" r="40" className="fill-akcent-myagkiy" />
      <circle cx="108" cy="66" r="6" className="fill-akcent" />

      {/* Граница, удержанная часть - сплошная и отчётливая. */}
      <path
        d="M74.29 41.36 A40 40 0 1 1 65.36 92"
        className="stroke-akcent"
        strokeWidth="2"
        strokeLinecap="round"
      />

      {/* Граница, разломанная часть - пунктир, через который проходят. */}
      <path
        d="M65.36 92 A40 40 0 0 1 74.29 41.36"
        className="stroke-granica-yarkaya"
        strokeWidth="2"
        strokeLinecap="round"
        strokeDasharray="2 6"
      />

      {/* Справа: чужое остановилось у сплошной линии и осталось снаружи. */}
      <circle
        cx="149"
        cy="80"
        r="7"
        className="fill-poverhnost stroke-granica-yarkaya"
        strokeWidth="1.5"
      />
      <circle
        cx="172"
        cy="46"
        r="4.5"
        className="fill-poverhnost stroke-granica"
        strokeWidth="1.5"
      />

      {/* Слева: чужое проходит через разрыв - снаружи, в проёме, уже внутри. */}
      <circle
        cx="28"
        cy="58"
        r="7"
        className="fill-poverhnost stroke-granica-yarkaya"
        strokeWidth="1.5"
      />
      <circle
        cx="60.6"
        cy="65"
        r="6"
        className="fill-poverhnost stroke-granica-yarkaya"
        strokeWidth="1.5"
      />
      <circle
        cx="84"
        cy="80"
        r="5"
        className="fill-poverhnost stroke-granica-yarkaya"
        strokeWidth="1.5"
      />
    </svg>
  );
}
