// Текст, который проявляется и разлетается по словам.
//
// Фаза 3 плана дизайна, заказ владелицы 13.09.2026: при переходе к
// следующему вопросу текст рассыпается - слова уходят вразлёт с расфокусом, а
// новый вопрос проявляется тем же движением в обратную сторону.
//
// Сама анимация - в globals.css, классы slovo и razlet. Этот файл только
// режет текст на слова и выдаёт каждому его задержку и направление разлёта.
//
// Почему на CSS, а не библиотекой motion. Тот же выбор, что для появления
// блоков в фазе 2: CSS срабатывает сразу, без ожидания JavaScript, и уже
// уважает системную настройку «уменьшить движение» - см. globals.css.
//
// Почему по словам, а не по буквам. По буквам эффектнее ровно один раз,
// дальше мешает: глаз пытается дочитать распадающееся слово. Переход
// случится двенадцать раз за тест.

import { Fragment, type CSSProperties } from "react";

// Длительности - те же числа, что в globals.css. Поменяли там - поменять и
// здесь: по этим числам экран вопроса решает, когда показывать следующий.
export const DLITELNOST_UKHODA = 200;
export const DLITELNOST_POYAVLENIYA = 240;

// Волна по словам: соседние слова стартуют с разницей до 25 мс, но вся волна
// укладывается в 80 мс, сколько бы слов ни было на экране. Без потолка
// длинный вопрос с пятью вариантами - это шестьдесят слов - разлетался бы
// полторы секунды.
//
// Итого разлёт не дольше 200 + 80 = 280 мс. Сверху набегает ещё около 55 мс -
// таймер, перерисовка, кадр браузера: замер в настоящем Chrome 14.09.2026
// показал, что при расчётных 320 мс следующий вопрос появлялся через
// 373-378 мс, дольше, чем разрешает план (250-350). Поэтому числа сокращены
// с 220 и 100 до 200 и 80.
const MAKS_SHAG = 25;
const MAKS_VOLNA = 80;

export function shagZaderzhki(vsegoSlov: number): number {
  if (vsegoSlov <= 1) return 0;
  return Math.min(MAKS_SHAG, MAKS_VOLNA / (vsegoSlov - 1));
}

export function razbitNaSlova(tekst: string): string[] {
  return tekst.trim().split(/\s+/).filter(Boolean);
}

export function schitatSlova(tekst: string): number {
  return razbitNaSlova(tekst).length;
}

// Разброс слова: куда улетает и на сколько поворачивается. Число от 0 до 1,
// зависит только от номера слова.
//
// Не Math.random намеренно. React требует, чтобы отрисовка давала одно и то
// же при одних и тех же данных, и проверка кода отклоняет случайные числа
// внутри неё - так уже было с Date.now в фазе 2 основного плана. Здесь разброс
// выглядит случайным, но при каждой отрисовке одинаков.
function razbros(n: number): number {
  const x = Math.sin(n * 12.9898 + 78.233) * 43758.5453;
  return x - Math.floor(x);
}

export function Slova({
  tekst,
  nachalo,
  shag,
}: {
  tekst: string;
  // Порядковый номер первого слова этого текста среди всех слов на экране.
  // Нужен, чтобы волна шла через вопрос и все варианты подряд, а не
  // начиналась заново в каждом.
  nachalo: number;
  shag: number;
}) {
  const slova = razbitNaSlova(tekst);

  return (
    <>
      {/* Целый текст - для экранного диктора. Нарезанные слова ему не
          показываем: он зачитывал бы их по одному, с паузами. */}
      <span className="sr-only">{tekst}</span>
      <span aria-hidden="true">
        {slova.map((slovo, i) => {
          const n = nachalo + i;
          const stil = {
            "--zaderzhka": `${Math.round(n * shag)}ms`,
            // Вбок до 8 точек в любую сторону, вверх от 4 до 12, поворот до
            // 8 градусов. Мало, но в сумме с расфокусом читается как
            // рассыпание, а не как съезжание всего блока.
            "--dx": `${((razbros(n) - 0.5) * 16).toFixed(1)}px`,
            "--dy": `${(-(4 + razbros(n + 7) * 8)).toFixed(1)}px`,
            "--povorot": `${((razbros(n + 13) - 0.5) * 16).toFixed(1)}deg`,
          } as CSSProperties;

          return (
            <Fragment key={i}>
              <span className="slovo" style={stil}>
                {slovo}
              </span>
              {i < slova.length - 1 ? " " : null}
            </Fragment>
          );
        })}
      </span>
    </>
  );
}
