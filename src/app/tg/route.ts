// Короткий адрес записи: GET /tg уводит в телеграм.
//
// Зачем он нужен. Кнопка в письме сейчас не работает: сервис рассылки
// подменяет все ссылки на свой домен `geteml.com`, а тот не открывается у
// получателей (разбор - `plans/2026-09-28-ssylki-v-pismah.md`). Короткий адрес
// решает две задачи сразу:
//
//   1. В письме он стоит обычным текстом, а текст сервис не подменяет. Почтовые
//      программы сами делают такой адрес нажимаемым, и человек попадает к нам
//      напрямую.
//   2. Цель перехода остаётся под нашим управлением: сменится телеграм - правим
//      одну строку в `src/lib/ssylki.ts`, и письма, уже ушедшие людям, начнут
//      вести на новое место.
//
// Ответ 302, а не 308: перенаправление временное по смыслу - цель может
// поменяться, и постоянный код браузеры кешируют надолго.

import { NextResponse } from "next/server";
import { TELEGRAM } from "@/lib/ssylki";

export function GET() {
  return NextResponse.redirect(TELEGRAM, 302);
}
