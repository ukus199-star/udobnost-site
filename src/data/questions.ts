/**
 * Пять типов ответа. В test-design.md они обозначены буквами,
 * здесь названы словами - так понятнее при чтении кода.
 *
 *   rescuer       С  Спасатель
 *   perfectionist О  Отличница
 *   peacemaker    М  Миротворец
 *   carrier       Т  Тот, на ком всё держится
 *   boundary      Д  своя граница
 */
export type TypeCode =
  | "rescuer"
  | "perfectionist"
  | "peacemaker"
  | "carrier"
  | "boundary";

/**
 * Порядок приоритета при ничьей - НЕ порядок перечисления.
 *
 * Если два типа набрали поровну, побеждает тот, кто стоит в этом списке выше.
 * Порядок задан владелицей практики: это решение о том, какой способ важнее
 * назвать человеку первым, а не техническая мелочь.
 *
 * boundary в сравнении не участвует: его выборы считаются раньше и отдельно,
 * порогом. Он оставлен в списке, чтобы порядок читался целиком.
 *
 * Источник: test-design.md, раздел «Как считается результат».
 */
export const typePriority: TypeCode[] = [
  "boundary",
  "rescuer",
  "carrier",
  "perfectionist",
  "peacemaker",
];

/**
 * Порог для результата «С границами в порядке»: сколько раз из двенадцати нужно
 * выбрать «свою границу». Сравнение включающее - ровно шесть уже засчитывается.
 *
 * Это абсолютное число выборов, а не доля от числа вопросов. Если вопросов
 * станет больше или меньше двенадцати, порог придётся пересмотреть руками.
 *
 * Величина стартовая: в test-design.md сказано, что после первых полусотни
 * прохождений её можно сдвинуть. Поэтому она живёт здесь одна, а не вписана
 * в условие.
 */
