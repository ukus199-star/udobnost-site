// Короткий адрес записи, набранный не теми буквами.
//
// Адрес kustova-psy.ru/tg сделан для того, чтобы его диктовали голосом и
// набирали руками, а телефонная клавиатура сама ставит первую букву заглавной.
// Пути в адресах чувствительны к регистру, поэтому /TG и /Tg отдавали
// «страница не найдена» - проверено на боевом сайте 28.09.2026. Теряется при
// этом человек, который уже решил написать, то есть самый дорогой.
//
// Почему не через redirects в next.config.ts: правила там сопоставляются БЕЗ
// учёта регистра, поэтому правило для /TG ловило и сам /tg - адрес начинал
// перенаправлять на себя. Поймано запуском: все написания отвечали 307 на
// /tg по кругу. Здесь регистр сравнивается явно, и настоящий /tg до правила
// не доходит.

import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";

export function proxy(request: NextRequest) {
  const put = request.nextUrl.pathname;

  // Точное совпадение пропускаем: его обслуживает src/app/tg/route.ts.
  if (put !== "/tg" && put.toLowerCase() === "/tg") {
    const pravilnyy = new URL("/tg", request.url);
    return NextResponse.redirect(pravilnyy, 307);
  }

  return NextResponse.next();
}

// Прослойка включается только на этом пути, чтобы не стоять на дороге у
// остальных запросов - главной страницы, приёма событий и формы почты.
export const config = {
  // Написания перечислены целиком. Сопоставление оказалось чувствительным к
  // регистру - проверено запуском: с одним "/tg" адрес /TG по-прежнему отдавал
  // 404. Для двух букв вариантов всего четыре, так что перебор здесь полный.
  matcher: ["/tg", "/tG", "/Tg", "/TG"],
};
