// Короткие адреса, набранные не теми буквами, и публичный адрес теста.
//
// Адрес kustova-psy.ru/tg сделан для того, чтобы его диктовали голосом и
// набирали руками, а телефонная клавиатура сама ставит первую букву заглавной.
// Пути в адресах чувствительны к регистру, поэтому /TG и /Tg отдавали
// «страница не найдена» - проверено на боевом сайте 28.09.2026. Теряется при
// этом человек, который уже решил написать, то есть самый дорогой.
//
// Почему не через redirects в next.config.ts: правила там сопоставляются БЕЗ
// учёта регистра, поэтому правило для /TG ловило и сам /tg - адрес начинал
// перенаправлять на себя. Поймано запуском: все написания отвечали 307 на
// /tg по кругу. Здесь регистр сравнивается явно, и настоящий /tg до правила
// не доходит.

import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";
import { PUT_TESTA } from "@/lib/ssylki";

export function proxy(request: NextRequest) {
  const put = request.nextUrl.pathname;

  // Точное совпадение пропускаем: его обслуживает src/app/tg/route.ts.
  if (put !== "/tg" && put.toLowerCase() === "/tg") {
    const pravilnyy = new URL("/tg", request.url);
    return NextResponse.redirect(pravilnyy, 307);
  }

  // Публичный адрес теста в любом написании ведёт на главную, где стоит тест.
  // Метки после «?» (utm из инстаграма) переносятся как есть. Код 307, а не
  // постоянный 308: когда тест переедет, цель поменяется, а постоянный
  // браузеры запоминают надолго.
  if (put.toLowerCase() === PUT_TESTA) {
    const glavnaya = new URL("/", request.url);
    glavnaya.search = request.nextUrl.search;
    return NextResponse.redirect(glavnaya, 307);
  }

  return NextResponse.next();
}

// Прослойка включается только на этих путях, чтобы не стоять на дороге у
// остальных запросов - главной страницы, приёма событий и формы почты.
export const config = {
  // Сопоставление чувствительно к регистру - проверено запуском: с одним
  // "/tg" адрес /TG по-прежнему отдавал 404. Для /tg написаний всего четыре,
  // они перечислены. Для /test их шестнадцать, поэтому шаблон: каждая буква в
  // двух вариантах. Значения здесь обязаны быть буквальными, константа из
  // ssylki.ts сюда не подставится.
  matcher: ["/tg", "/tG", "/Tg", "/TG", "/([tT][eE][sS][tT])"],
};
