// Файл с особым именем: Next.js сам вызывает register один раз при старте
// сервера, до того как придёт первый посетитель. Место для того, что нужно
// сделать ровно однажды - у нас это создание таблицы в базе.

export async function register() {
  // register вызывается во всех средах выполнения, а библиотека pg работает
  // только в полноценном Node. Импорт внутри условия, а не наверху файла:
  // иначе pg попал бы туда, где его нет.
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  const { ensureSchema } = await import("./lib/db");

  // Результат не проверяем и ничего не прерываем: сайт обязан подняться даже
  // с недоступной базой. Что случилось, видно в логах приложения на Amvera.
  await ensureSchema();
}
